"""Turn results/runs/* into the tables and plots used in the README.

    python scripts/analyze_results.py

Writes results/plots/*.png and results/analysis.md (tables for every experiment,
late-event and restart evidence, Bloom false-positive example, LSH trade-off).
"""
import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "results" / "runs"
PLOTS = ROOT / "results" / "plots"


def load_json(run, name):
    p = RUNS / run / name
    return json.loads(p.read_text()) if p.exists() else {}


def load_csv(path):
    if not path.exists():
        return []
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def summary_rows():
    return {r["run_id"]: r for r in load_csv(ROOT / "results" / "experiment_summary.csv")}


def fmt(v, nd=1):
    if v in (None, "", "None"):
        return "-"
    try:
        f = float(v)
        return f"{f:,.{nd}f}" if not f.is_integer() or nd == 0 else f"{int(f):,}"
    except (TypeError, ValueError):
        return str(v)


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def plot_lag(runs, title, fname, events=None):
    fig, ax = plt.subplots(figsize=(8, 3.6))
    for run in runs:
        rows = load_csv(RUNS / run / "lag_timeline.csv")
        rows = [r for r in rows if r["lag_raw_stage1"] not in ("", "None")]
        if not rows:
            continue
        t = [float(r["t_s"]) for r in rows]
        ax.plot(t, [int(r["lag_raw_stage1"]) for r in rows], label=f"{run} taxi.raw (Stage 1)")
        ax.plot(t, [int(r["lag_clean_stage2"] or 0) for r in rows], "--", label=f"{run} taxi.clean (Stage 2)")
    for ev in events or []:
        ax.axvline(ev["t_s"], color="grey", lw=0.8, ls=":")
        ax.text(ev["t_s"], ax.get_ylim()[1] * 0.95, ev["event"], rotation=90, va="top", fontsize=7)
    ax.set_xlabel("seconds since stages started")
    ax.set_ylabel("consumer lag (messages)")
    ax.set_title(title)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(PLOTS / fname, dpi=130)
    plt.close(fig)


def main():
    PLOTS.mkdir(parents=True, exist_ok=True)
    S = summary_rows()
    md = ["# Experiment analysis (generated by scripts/analyze_results.py)\n"]

    # ---------------------------------------------------------------- partition / consumer
    cols = ["run", "partitions", "slots", "key", "requested/s", "produced/s", "stage1/s", "stage2/s",
            "p50 ms", "p95 ms", "max lag raw", "max lag clean", "skew raw"]

    def perf_row(r):
        return [r["run_id"], r["partitions"], r["parallelism"], r["partition_key"], fmt(r["requested_rate"], 0),
                fmt(r["produced_eps"]), fmt(r["stage1_eps"]), fmt(r["stage2_eps"]), fmt(r["latency_p50_ms"], 0),
                fmt(r["latency_p95_ms"], 0), fmt(r["max_lag_raw"], 0), fmt(r["max_lag_clean"], 0),
                fmt(r["skew_raw"], 3)]
    for title, ids in (("7.2 Partitions / consumers", ["P1", "P2", "P3", "P4"]),
                       ("7.3 Partition key", ["K1", "K2"])):
        rows = [perf_row(S[i]) for i in ids if i in S]
        if rows:
            md += [f"## {title}\n", table(cols, rows), ""]
    pc = []
    for run in ("K1", "K2"):
        c = load_json(run, "partition_counts.json").get("taxi.raw")
        if c:
            pc.append([run] + [fmt(c.get(str(p), c.get(p)), 0) for p in range(4)])
    if pc:
        md += ["Messages per taxi.raw partition:\n", table(["run", "p0", "p1", "p2", "p3"], pc), ""]

    # ---------------------------------------------------------------- rates
    rate_cols = ["rate", "produced/s", "processed/s (Stage 2)", "p50 latency ms", "p95 latency ms",
                 "max lag (raw / clean)", "HLL err %", "DGIM err % (k=5000)", "sampling err % (k=1000)",
                 "LSH recall 20x5"]
    rows = []
    for i in ("R-low", "R-medium", "R-high"):
        if i in S:
            r = S[i]
            rows.append([i, fmt(r["produced_eps"]), fmt(r["stage2_eps"]), fmt(r["latency_p50_ms"], 0),
                         fmt(r["latency_p95_ms"], 0), f"{fmt(r['max_lag_raw'], 0)} / {fmt(r['max_lag_clean'], 0)}",
                         fmt(r["hll_mean_error_pct"], 3), fmt(r["dgim_error_pct"], 2),
                         fmt(r["sampling_error_pct"], 2), fmt(r["lsh_recall_default"], 3)])
    if rows:
        md += ["## 7.4 Producer rate\n", table(rate_cols, rows), ""]
        plot_lag(["R-low", "R-medium", "R-high"], "Consumer lag at low / medium / high input rate", "lag_rates.png")
    plot_lag(["P1", "P2", "P3", "P4"], "Consumer lag, partition/consumer runs", "lag_partitions.png")

    # throughput bar chart
    ids = [i for i in ("P1", "P2", "P3", "P4", "K1", "K2", "R-low", "R-medium", "R-high") if i in S]
    if ids:
        fig, ax = plt.subplots(figsize=(8, 3.4))
        x = range(len(ids))
        ax.bar([i - 0.2 for i in x], [float(S[i]["stage1_eps"] or 0) for i in ids], 0.4, label="Stage 1 ev/s")
        ax.bar([i + 0.2 for i in x], [float(S[i]["stage2_eps"] or 0) for i in ids], 0.4, label="Stage 2 ev/s")
        ax.plot(list(x), [float(S[i]["produced_eps"] or 0) for i in ids], "k_", ms=22, mew=2, label="produced ev/s")
        ax.set_xticks(list(x))
        ax.set_xticklabels(ids)
        ax.set_ylabel("events / second")
        ax.legend(fontsize=8)
        ax.set_title("Throughput per run")
        fig.tight_layout()
        fig.savefig(PLOTS / "throughput.png", dpi=130)
        plt.close(fig)

    # ---------------------------------------------------------------- algorithms (default run)
    d = load_json("default", "final_summary.json")
    if d:
        b = d["bloom"]
        md += ["## Default run: algorithm quality\n",
               f"Bloom: m = {b['bit_array_size']:,} bits ({b['memory_bytes']:,} bytes), k = {b['num_hashes']}, "
               f"inserted IDs = {b['inserted_ids']:,}, true duplicates = {b['true_duplicates']}, "
               f"flagged = {b['true_duplicates_flagged']}, false positives = {b['false_positives']} "
               f"(FP rate {b['fp_rate']}), false negatives = {b['false_negatives']} (FN rate {b['fn_rate']}).\n"]
        rows = [[x["k"], x["exact_mean_fare"], x["sample_mean_fare"], x["fare_error_pct"],
                 x["exact_mean_distance"], x["sample_mean_distance"], x["distance_error_pct"]]
                for x in d["sampling"]["by_k"]]
        md += ["Reservoir sampling (whole stream):\n",
               table(["k", "exact mean fare", "sample mean fare", "err %", "exact mean dist", "sample mean dist",
                      "err %"], rows), ""]
        rows = [[x["k"], x["exact_ones"], x["estimate"], x["abs_error"], x["error_pct"]] for x in d["dgim"]["by_k"]]
        md += [f"DGIM (N = {d['dgim']['N']}, buckets stored = {d['dgim']['buckets']}):\n",
               table(["k", "exact 1s", "DGIM estimate", "abs error", "error %"], rows), ""]
    recs = [json.loads(line) for line in (RUNS / "default" / "results.jsonl").read_text().splitlines()
            if line.strip()] if (RUNS / "default" / "results.jsonl").exists() else []
    wins = sorted((r for r in recs if r.get("type") != "run_summary" and r.get("hll")),
                  key=lambda r: r["window_start"])
    if wins:
        rows = [[w["window_start"][5:16], w["events_in_window"], w["hll"]["exact_routes"], w["hll"]["estimate"],
                 w["hll"]["error_pct"],
                 (w.get("diversity") or {}).get("exact_fraction_diverse"),
                 ((w.get("diversity") or {}).get("event_sampling") or {}).get("estimate"),
                 ((w.get("diversity") or {}).get("entity_sampling") or {}).get("estimate"),
                 (w.get("lsh") or {}).get("active_zones"), (w.get("lsh") or {}).get("true_pairs"),
                 (w.get("lsh") or {}).get("candidates"), (w.get("lsh") or {}).get("recall")] for w in wins]
        h = wins[0]["hll"]
        md += [f"Per-window results, default run (HLL++ p = {h['precision']}, {h['registers']} registers, "
               f"~{h['sketch_bytes']} bytes per sketch vs ~{h['exact_set_bytes_est']:,} bytes for the exact set "
               f"in the first window):\n",
               table(["window", "events", "exact routes", "HLL", "HLL err %", "diverse exact", "event-sample",
                      "entity-sample", "LSH zones", "true pairs", "candidates 20x5", "recall 20x5"], rows), ""]
        # diversity plot
        fig, ax = plt.subplots(figsize=(8, 3.4))
        xs = list(range(len(wins)))
        div = [w.get("diversity") or {} for w in wins]
        ax.plot(xs, [x.get("exact_fraction_diverse") for x in div], "k-o", ms=3, label="exact")
        ax.plot(xs, [(x.get("event_sampling") or {}).get("estimate") for x in div], "-s", ms=3,
                label="event sampling (10% of events)")
        ax.plot(xs, [(x.get("entity_sampling") or {}).get("estimate") for x in div], "-^", ms=3,
                label="entity sampling (same storage)")
        ax.set_xticks(xs)
        ax.set_xticklabels([w["window_start"][11:13] for w in wins], fontsize=7)
        ax.set_xlabel("window start hour (2026-01-05)")
        ax.set_ylabel("fraction of zones diverse")
        ax.legend(fontsize=8)
        ax.set_title("Non-linear statistic: event vs entity sampling")
        fig.tight_layout()
        fig.savefig(PLOTS / "diversity.png", dpi=130)
        plt.close(fig)
    if d:
        rows = [[k, v["mean_recall"], v["mean_candidate_precision"], v["mean_candidate_reduction"],
                 v["total_candidates"], v["total_true_pairs"], v["mean_lsh_latency_ms"]]
                for k, v in d["lsh_by_setting"].items()]
        md += ["LSH settings (default run, averaged over windows):\n",
               table(["bands x rows", "mean recall", "mean cand. precision", "mean cand. reduction",
                      "total candidates", "total true pairs", "mean LSH ms"], rows),
               f"\nMean exact all-pairs latency: {d['mean_exact_latency_ms']} ms.\n",
               f"Diversity mean absolute error: {d['diversity_mean_abs_error']}\n"]

    # ---------------------------------------------------------------- late events
    if d:
        late = d["late_events"]
        md += ["## 8.1 Late events (default run)\n",
               f"Classes (Stage 2 mirror of the Spark watermark): {json.dumps(late)}\n",
               f"Rows Spark reported as dropped by the watermark: {d.get('spark_rows_dropped_by_watermark')}\n"]
        delayed = {r["event_id"]: r for r in load_csv(RUNS / "default" / "producer_delayed.csv")}
        dropped = {}
        p = RUNS / "default" / "late_dropped_ids.csv"
        if p.exists():
            for line in p.read_text().splitlines():
                eid, et, lateness = line.split(",")
                dropped[eid] = (et, float(lateness))
        if delayed and (RUNS / "default" / "late_dropped_ids.csv").exists():
            dd = [e for e in delayed if e in dropped]
            md += [f"Producer delayed {len(delayed)} events; {len(dd)} of them were dropped as too late, "
                   f"{len(delayed) - len(dd)} were still counted. {len(dropped) - len(dd)} dropped events were "
                   f"not deliberately delayed (natural out-of-order across partitions/batches).\n"]
            ex = sorted(dd, key=lambda e: -float(delayed[e]["delay_s"]))[:3]
            for e in ex:
                md.append(f"* dropped: `{e}` event_time {delayed[e]['event_time']}, held back "
                          f"{delayed[e]['delay_s']} s by the producer, {dropped[e][1]} min of event time behind "
                          f"the stream when it arrived")
            inc = [e for e in delayed if e not in dropped]
            inc = sorted(inc, key=lambda e: -float(delayed[e]["delay_s"]))[:2]
            for e in inc:
                md.append(f"* included: `{e}` event_time {delayed[e]['event_time']}, held back "
                          f"{delayed[e]['delay_s']} s, its window was still open")
            md.append("")
        st2 = load_json("default", "stage2_stats.json")
        if st2.get("late", {}).get("examples"):
            md += ["Examples recorded by Stage 2:\n", "```json",
                   json.dumps(st2["late"]["examples"][:4], indent=1), "```", ""]

    # ---------------------------------------------------------------- restart
    rs = load_json("restart", "final_summary.json")
    ev = load_json("restart", "restart_events.json") if (RUNS / "restart" / "restart_events.json").exists() else []
    if rs:
        log2 = (RUNS / "restart" / "stage2.log").read_text(errors="ignore") if (RUNS / "restart" / "stage2.log").exists() else ""
        restored = [line for line in log2.splitlines() if "restored state" in line or "skipped" in line]
        lag = load_csv(RUNS / "restart" / "lag_timeline.csv")
        md += ["## 8.2 Restart / recovery (run `restart`)\n",
               f"Events: {json.dumps(ev)}\n",
               f"Max taxi.clean lag during the outage: {S.get('restart', {}).get('max_lag_clean')}; "
               f"events processed at the end: {rs.get('events_processed')} "
               f"(default run without restart: {d.get('events_processed') if d else '-'}).\n",
               "Stage 2 log lines:\n", "```", *restored[:6], "```", ""]
        if lag:
            plot_lag(["restart"], "Stage 2 killed and restarted while the producer runs", "lag_restart.png", ev)

    # ---------------------------------------------------------------- bloom small
    bs = load_json("bloom-small", "stage1_stats.json")
    if bs:
        b = bs["bloom"]
        md += ["## Bloom filter false-positive demonstration (run `bloom-small`)\n",
               f"bloom_expected_items = 2000 for a stream of {b['inserted_ids']:,} distinct IDs: m = "
               f"{b['bit_array_size']:,} bits, k = {b['num_hashes']}; FP = {bs['bloom_fp']:,} "
               f"(rate {b['fp_rate']}), FN = {bs['bloom_fn']} (rate {b['fn_rate']}).\n",
               "First false positives (event_id never seen before, filter said 'seen'):\n", "```json",
               json.dumps(bs["fp_examples"][:3], indent=1), "```", ""]
    s1 = load_json("default", "stage1_stats.json")
    if s1:
        md += [f"Default run Stage 1: accepted {s1['accepted']:,}, rejected {s1['rejected']:,} "
               f"{json.dumps(s1['reject_reasons'])}; false-positive examples: {s1['fp_examples'][:2]}\n"]

    (ROOT / "results" / "analysis.md").write_text("\n".join(md), encoding="utf-8")
    print(f"wrote results/analysis.md and {len(list(PLOTS.glob('*.png')))} plots")


if __name__ == "__main__":
    sys.exit(main())
